"""Generator for blind test set. Amounts for fraud items follow CSRC decisions; see report for inferences."""
import json
from decimal import Decimal, ROUND_HALF_UP

D = lambda x: Decimal(str(x))
def r2(x): return float(D(x).quantize(Decimal("0.01"), ROUND_HALF_UP))

def E(code, name, dr=0, cr=0, s=""):
    return {"account_code": code, "account_name": name, "debit": r2(dr), "credit": r2(cr), "summary": s}

def V(vid, date, prep, chk, att, doc, entries):
    return {"voucher_id": vid, "voucher_date": date, "preparer": prep, "checker": chk,
            "attachments_count": att, "associated_doc_id": doc, "entries": entries}

def C(cid, cp, date, amt, terms, deliv, rp=False):
    return {"contract_id": cid, "customer_or_vendor": cp, "sign_date": date, "total_amount": r2(amt),
            "payment_terms": terms, "delivery_condition": deliv, "is_related_party": rp}

def I(no, date, buyer, seller, net, rate, goods, tax=None):
    net = D(net)
    t = (net * D(rate)).quantize(Decimal("0.01"), ROUND_HALF_UP) if tax is None else D(tax)
    return {"invoice_no": no, "invoice_date": date, "buyer_name": buyer, "seller_name": seller,
            "amount_without_tax": r2(net), "tax_amount": r2(t), "total_amount": r2(net + t), "goods_or_service": goods}

def tax_of(net, rate):
    return (D(net) * D(rate)).quantize(Decimal("0.01"), ROUND_HALF_UP)

def bank(opening, rows):
    """rows: (id, time, cp, acct, amount, remark). returns list with running balance."""
    bal = D(opening); out = []
    for tid, t, cp, ac, amt, rm in rows:
        bal += D(amt)
        out.append({"transaction_id": tid, "transaction_time": t, "counterparty_name": cp,
                    "counterparty_account": ac, "amount": r2(amt), "balance_after": r2(bal), "remark": rm})
    return out

def F(ftype, lvl, amt, vouchers, clause):
    return {"finding_type": ftype, "expected_risk_level": lvl, "expected_amount": r2(amt),
            "expected_vouchers": vouchers, "standard_clause": clause}

