"""Build blind test set v2 (10 fraud + 6 compliance). Amounts in CNY."""
import json, datetime

def r2(x): return round(x + 1e-9, 2)
def E(code, name, dr=0.0, cr=0.0, s=""):
    return {"account_code": code, "account_name": name, "debit": r2(dr), "credit": r2(cr), "summary": s}

class Case:
    def __init__(s, **kw):
        s.d = dict(kw); s.d.update(vouchers=[], contracts=[], invoices=[], bank_flows=[], ground_truth_findings=[])
        s._flows = []; s.open_bal = kw.pop("_open", 0) if "_open" in kw else 0
    def v(s, vid, date, prep, chk, att, doc, entries, bank=None):
        """bank: (time 'HH:MM', counterparty, acct, remark, txn_id) - amount derived from 1002 lines"""
        s.d["vouchers"].append(dict(voucher_id=vid, voucher_date=date, preparer=prep, checker=chk,
                                     attachments_count=att, associated_doc_id=doc, entries=entries))
        if bank:
            t, cp, acct, rmk, tid = bank
            amt = sum(e["debit"] - e["credit"] for e in entries if e["account_code"].startswith("1002"))
            s._flows.append(dict(transaction_id=tid, transaction_time=f"{date} {t}", counterparty_name=cp,
                                 counterparty_account=acct, amount=r2(amt), remark=rmk))
    def flow(s, tid, ts, cp, acct, amt, rmk):
        s._flows.append(dict(transaction_id=tid, transaction_time=ts, counterparty_name=cp,
                             counterparty_account=acct, amount=r2(amt), remark=rmk))
    def c(s, cid, cp, date, total, terms, cond, rel=False):
        s.d["contracts"].append(dict(contract_id=cid, customer_or_vendor=cp, sign_date=date, total_amount=r2(total),
                                     payment_terms=terms, delivery_condition=cond, is_related_party=rel))
    def inv(s, no, date, buyer, seller, net, rate, goods):
        tax = r2(net * rate)
        s.d["invoices"].append(dict(invoice_no=no, invoice_date=date, buyer_name=buyer, seller_name=seller,
                                    amount_without_tax=r2(net), tax_amount=tax, total_amount=r2(net + tax),
                                    goods_or_service=goods))
        return tax
    def f(s, ftype, lvl, amt, basis, vids, clause):
        s.d["ground_truth_findings"].append(dict(finding_type=ftype, expected_risk_level=lvl, expected_amount=r2(amt),
                                                 amount_basis=basis, expected_vouchers=vids, standard_clause=clause))
    def done(s, opening):
        bal = opening
        for fl in sorted(s._flows, key=lambda x: x["transaction_time"]):
            bal = r2(bal + fl["amount"]); fl["balance_after"] = bal
            s.d["bank_flows"].append(fl)
        return s.d

