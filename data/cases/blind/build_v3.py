def r2(x): return round(x + 1e-9, 2)

class Case:
    def __init__(s, cid, name, code, industry, period, opening, acct):
        s.d = dict(case_id=cid, company_name=name, stock_code=code, penalty_decision_no='', source_url='',
                   case_category='', csrc_summary='', industry=industry, audit_period=period, description='',
                   vouchers=[], contracts=[], invoices=[], bank_flows=[], ground_truth_findings=[])
        s.name = name; s.opening = opening; s.acct = acct; s._flows = []
    def E(s, code, dr=0.0, cr=0.0, summ=''):
        return dict(account_code=code, account_name=NAMES[code], debit=r2(dr), credit=r2(cr), summary=summ)
    def V(s, vid, date, entries, prep, chk, att=2, doc='', bank=None):
        s.d['vouchers'].append(dict(voucher_id=vid, voucher_date=date, preparer=prep, checker=chk,
                                    attachments_count=att, associated_doc_id=doc, entries=entries))
        net = r2(sum(e['debit'] - e['credit'] for e in entries if e['account_code'] == '1002'))
        if net != 0:
            assert bank, vid
            t, cp, ca = bank
            s._flows.append(dict(transaction_id='', transaction_time=t, counterparty_name=cp,
                                 counterparty_account=ca, amount=net, remark=entries[0]['summary'], balance_after=0.0))
    def INV(s, no, date, buyer, seller, net, rate, goods):
        tax = r2(net * rate); tot = r2(net + tax)
        s.d['invoices'].append(dict(invoice_no=no, invoice_date=date, buyer_name=buyer, seller_name=seller,
                                    amount_without_tax=r2(net), tax_amount=tax, total_amount=tot, goods_or_service=goods))
        return r2(net), tax, tot
    def sale(s, vid, date, buyer, net, rate, goods, invno, prep, chk, summ, dr='1122', rev='6001', att=3, bank=None, extra=None):
        n, t, tot = s.INV(invno, date, buyer, s.name, net, rate, goods)
        en = [s.E(dr, tot, 0, summ), s.E(rev, 0, n, summ)]
        if t: en.append(s.E('2221', 0, t, summ + '-销项税额'))
        if extra: en += extra
        s.V(vid, date, en, prep, chk, att, invno, bank)
    def buy(s, vid, date, seller, net, rate, goods, invno, prep, chk, summ, dr='1403', cr='2202', att=3, bank=None):
        n, t, tot = s.INV(invno, date, s.name, seller, net, rate, goods)
        en = [s.E(dr, n, 0, summ)]
        if t: en.append(s.E('2221', t, 0, summ + '-进项税额'))
        en.append(s.E(cr, 0, tot, summ))
        s.V(vid, date, en, prep, chk, att, invno, bank)
    def CT(s, cid, cp, date, amt, pay, deliv, rel=False):
        s.d['contracts'].append(dict(contract_id=cid, customer_or_vendor=cp, sign_date=date, total_amount=r2(amt),
                                     payment_terms=pay, delivery_condition=deliv, is_related_party=rel))
    def F(s, ftype, risk, acct, side, vids, clause, basis_note):
        vs = {v['voucher_id']: v for v in s.d['vouchers']}
        amt = 0.0
        for vid in vids:
            for e in vs[vid]['entries']:
                if e['account_code'] == acct:
                    amt += e['debit'] if side == '借方' else e['credit']
        amt = r2(amt)
        basis = f"由凭证{'、'.join(vids)}中科目{acct}（{NAMES[acct]}）{side}金额合计得出，{basis_note}"
        s.d['ground_truth_findings'].append(dict(finding_type=ftype, expected_risk_level=risk, expected_amount=amt,
                                                 amount_basis=basis, expected_vouchers=vids, standard_clause=clause))
    def done(s):
        fl = sorted(s._flows, key=lambda x: x['transaction_time'])
        bal = s.opening
        for i, f in enumerate(fl, 1):
            bal = r2(bal + f['amount']); f['balance_after'] = bal
            f['transaction_id'] = f"{s.d['case_id'][-3:]}-BF{i:03d}"
        s.d['bank_flows'] = fl
        s.d['vouchers'].sort(key=lambda v: (v['voucher_date'], v['voucher_id']))
        return s.d

